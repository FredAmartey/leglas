describe.skipIf(findBrowser() === null)("a generation, end to end", () => {
  test.skipIf(process.env.CODEX_SANDBOX === "seatbelt")(
    "plans, builds all at once, repairs a broken direction, stops one and replaces it",
    async () => {
      const cwd = await project("claude");
      const { server, log } = await leglas(cwd, true);
      const began = Date.now();

      const started = await call(server, "generate", {
        surface: "hero",
        brief: "A cooking app",
        count: 3,
      });

      expect(started.status).toBe(202);

      const building = await until(
        server,
        (current) =>
          current.slots.some((slot) => slot.title === "Slow Idea" && slot.state === "building"),
        "the slow direction to be building",
      );

      const slowFile = join(cwd, ".leglas", "variants", "hero", "hero-slow.tsx");

      // Wait until the slow build has written half its file, so the stop has something to undo.
      for (
        let tries = 0;
        tries < 200 && !(await readFile(slowFile, "utf8")).startsWith("// half written");
        tries += 1
      ) {
        await new Promise((resolve) => setTimeout(resolve, 50));
      }

      // Every concept is on the rail the moment the plan lands, before any build finishes.
      const registered = parseJson(await readFile(join(cwd, ".leglas", "previews.json"), "utf8"));

      const titles =
        isJsonRecord(registered) && Array.isArray(registered.previews)
          ? registered.previews.map((entry) => (isJsonRecord(entry) ? entry.title : null))
          : [];

      expect(titles).toEqual(["Plain Idea", "Broken Idea", "Slow Idea"]);

      const slow = required(building.slots.find((slot) => slot.title === "Slow Idea"));
      expect(
        (await call(server, "generate/stop", { id: building.id, slot: slow.key })).status,
      ).toBe(200);

      const settled = await until(
        server,
        (current) => current.state === "done",
        "the generation to settle",
      );

      const byTitle = new Map(settled.slots.map((slot) => [slot.title, slot]));

      expect(byTitle.get("Plain Idea")).toMatchObject({ state: "ready", fixed: false });
      expect(byTitle.get("Broken Idea")).toMatchObject({ state: "ready", fixed: true });
      expect(byTitle.get("Slow Idea")).toMatchObject({ state: "stopped" });
      // The stopped build's half-finished work does not stay on the rail.
      expect(
        await readFile(join(cwd, ".leglas", "variants", "hero", `${slow.key}.tsx`), "utf8"),
      ).toBe("export function HeroSlow() {\n  return null;\n}\n");

      const switchFile = await readFile(
        join(cwd, ".leglas", "variants", "hero", "switch.tsx"),
        "utf8",
      );

      for (const key of ["current", '"hero-a"', '"hero-plain"', '"hero-broken"', '"hero-slow"'])
        expect(switchFile).toContain(`  ${key}:`);

      expect(
        (await call(server, "generate/replace", { id: settled.id, slot: slow.key })).status,
      ).toBe(200);

      const replaced = await until(
        server,
        (current) =>
          current.state === "done" &&
          current.slots.some((slot) => slot.title === "Fresh Idea" && slot.state === "ready"),
        "the replacement",
      );

      const elapsed = Date.now() - began;

      // What Leglas sent: restricted runs at medium effort, and builders told the project's facts.
      const calls = (await readFile(log, "utf8"))
        .trim()
        .split("\n")
        .map((line) => parseJson(line))
        .map((entry) =>
          isJsonRecord(entry) && Array.isArray(entry.args) ? entry.args.map(String) : [],
        );

      for (const args of calls) {
        expect(args).toContain("--restricted");
        expect(args[args.indexOf("--effort") + 1]).toBe("medium");
      }

      const builds = calls.filter(
        (args) => args[args.indexOf("--tools") + 1] === "Read,Write,Edit",
      );

      const plain = required(
        builds.find((args) => args.some((arg) => arg.includes("Plain Idea, Big type"))),
      );

      const prompt = required(plain[plain.indexOf("-p") + 1]);

      expect(prompt).toContain("Leglas read the project for you.");
      expect(prompt).toContain("--accent: #d9542b;");
      expect(prompt).toContain("/photos/plate.jpg");
      expect(prompt).toContain(".leglas/variants/hero/current.tsx");

      // The repeatable artifact: the job as the interface sees it and a screenshot of each ready direction.
      await mkdir(ARTIFACTS, { recursive: true });
      await writeFile(
        join(ARTIFACTS, "summary.json"),
        `${JSON.stringify({ elapsedMs: elapsed, job: replaced, calls: calls.length }, null, 2)}\n`,
      );

      for (const slot of replaced.slots.filter((candidate) => candidate.state === "ready")) {
        const shot = await call(server, "capture", { title: slot.title });
        const file = shot.json.path ?? shot.json.file;

        if (isString(file))
          await copyFile(join(cwd, file), join(ARTIFACTS, `${slot.key}.png`)).catch(() => {});
      }

      // Everything but the fake agents' own sleeps is Leglas: planning, slots, renders and the fix run.
      expect(elapsed).toBeLessThan(30_000);
    },
    START_TIMEOUT_MS * 2,
  );
});
